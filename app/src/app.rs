//! Top-level application: login screen <-> main UI.

use crate::gpu::Gpu;
use crate::settings::Settings;
use crate::toasts::Toasts;
use crate::views::login::LoginView;
use crate::views::main_view::MainView;
use bi_media::audio::AudioOutput;

pub enum Screen {
    Login(LoginView),
    Main(Box<MainView>),
}

pub struct UiApp {
    pub settings: Settings,
    pub audio: AudioOutput,
    pub gpu: Option<Gpu>,
    pub toasts: Toasts,
    pub screen: Screen,
}

/// Shared services handed to views each frame.
pub struct Services<'a> {
    pub settings: &'a mut Settings,
    pub audio: &'a AudioOutput,
    pub gpu: &'a Gpu,
    pub toasts: &'a mut Toasts,
}

impl UiApp {
    pub fn new(cc: &eframe::CreationContext<'_>) -> Self {
        crate::views::style::apply(&cc.egui_ctx);
        let settings = Settings::load();
        let audio = AudioOutput::open();
        audio.set_volume(settings.f64("ui3_audioVolume") as f32);
        audio.set_muted(settings.bool("ui3_audioMute"));
        let gpu = cc.wgpu_render_state.as_ref().map(|_| ()).and_then(|_| None::<Gpu>);
        let login = LoginView::new(&settings);
        UiApp { settings, audio, gpu, toasts: Toasts::default(), screen: Screen::Login(login) }
    }
}

impl eframe::App for UiApp {
    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut eframe::Frame) {
        if self.gpu.is_none() {
            self.gpu = Gpu::from_frame(frame);
            if let Some(g) = &self.gpu {
                tracing::info!("GPU: {} ({})", g.adapter_name, g.backend);
            }
        }
        let Some(gpu) = self.gpu.clone() else {
            ui.label("wgpu renderer unavailable");
            return;
        };
        gpu.apply_zero_copy(self.settings.native.zero_copy);
        let ctx = ui.ctx().clone();
        let mut next: Option<Screen> = None;
        match &mut self.screen {
            Screen::Login(l) => {
                if let Some(main) = l.ui(ui, &mut self.settings, &mut self.toasts) {
                    next = Some(Screen::Main(Box::new(main)));
                }
            }
            Screen::Main(m) => {
                let mut svc = Services { settings: &mut self.settings, audio: &self.audio, gpu: &gpu, toasts: &mut self.toasts };
                if m.ui(ui, frame, &mut svc) {
                    m.shutdown(&gpu);
                    ctx.send_viewport_cmd(egui::ViewportCommand::Title("UI3 Native".into()));
                    next = Some(Screen::Login(LoginView::after_logout(&self.settings)));
                }
            }
        }
        if let Some(n) = next {
            self.screen = n;
        }
        self.toasts.show(&ctx);
        self.settings.save_if_dirty();
    }

    fn on_exit(&mut self) {
        if let (Screen::Main(m), Some(g)) = (&mut self.screen, &self.gpu) {
            m.shutdown(g);
        }
        self.settings.save();
    }
}

/// Window icon (embedded at build time; generated by tools/gen/gen_app_icon.py).
pub fn icon() -> egui::IconData {
    let bytes = include_bytes!("../assets/icon64.rgba");
    egui::IconData { rgba: bytes.to_vec(), width: 64, height: 64 }
}
